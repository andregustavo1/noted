const stored = () => {
    try { return JSON.parse(localStorage.getItem("settings") || "{}").language; } catch { return undefined; }
};

let language = stored() === "en" ? "en" : "pt";

export const setLanguage = (next) => {
    language = next === "en" ? "en" : "pt";
    document.documentElement.lang = language === "en" ? "en" : "pt-BR";
};
setLanguage(language);

export const t = (pt) => (language === "en" && EN[pt]) || pt;
// For dates, number formats and name sorting.
export const locale = () => (language === "en" ? "en-US" : "pt-BR");
export const weekdays = () => (language === "en" ? ["S", "M", "T", "W", "T", "F", "S"] : ["D", "S", "T", "Q", "Q", "S", "S"]);
